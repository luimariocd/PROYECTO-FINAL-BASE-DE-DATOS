-- REQUERIMIENTO 4.1 - ELECCION DE BAJADA POR BOLETO
-- I = registrar, U = cambiar, D = quitar (si la regla de negocio lo permite).
-- Sin COMMIT: integrar con la misma transaccion de la venta del boleto.
CREATE OR REPLACE PROCEDURE LEHZ_GES_BAJADA (
    P_OPERACION IN VARCHAR2,
    P_ID_BOLETO IN NUMBER,
    P_ID_PUNTO_BAJADA IN NUMBER DEFAULT NULL
)
IS
    V_ID_RUTA NUMBER;
    V_EXISTE NUMBER;
BEGIN
    -- Bloquea el boleto: evita dos altas concurrentes por el mismo boleto.
    SELECT V.ID_RUTA INTO V_ID_RUTA
      FROM LEHZ_BOLETO B JOIN LEHZ_VIAJE V ON V.ID_VIAJE = B.ID_VIAJE
     WHERE B.ID_BOLETO = P_ID_BOLETO
     FOR UPDATE OF B.ID_BOLETO;

    IF UPPER(TRIM(P_OPERACION)) IN ('I','U') THEN
        SELECT COUNT(*) INTO V_EXISTE
          FROM LEHZ_PUNTO_BAJADA PB
          JOIN LEHZ_RUTA R ON R.ID_RUTA = PB.ID_RUTA
         WHERE PB.ID_PUNTO_BAJADA = P_ID_PUNTO_BAJADA
           AND PB.ID_RUTA = V_ID_RUTA
           AND PB.ID_TERMINAL <> R.ID_TERMINAL_ORIGEN
           AND (PB.ID_TERMINAL = R.ID_TERMINAL_DESTINO OR EXISTS (
                SELECT 1 FROM LEHZ_RUTA_PARADA RP
                 WHERE RP.ID_RUTA = PB.ID_RUTA
                   AND RP.ID_TERMINAL = PB.ID_TERMINAL));
        IF V_EXISTE = 0 THEN
            RAISE_APPLICATION_ERROR(-20111, 'Bajada no habilitada para la ruta del boleto');
        END IF;
    END IF;

    IF UPPER(TRIM(P_OPERACION)) = 'I' THEN
        INSERT INTO LEHZ_PASAJE_BAJADA(ID_PASAJE_BAJADA, ID_BOLETO, ID_PUNTO_BAJADA)
        VALUES(LEHZ_SEQ_PASAJE_BAJADA.NEXTVAL, P_ID_BOLETO, P_ID_PUNTO_BAJADA);
    ELSIF UPPER(TRIM(P_OPERACION)) = 'U' THEN
        UPDATE LEHZ_PASAJE_BAJADA SET ID_PUNTO_BAJADA = P_ID_PUNTO_BAJADA
         WHERE ID_BOLETO = P_ID_BOLETO;
        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20112, 'El boleto no tiene bajada registrada');
        END IF;
    ELSIF UPPER(TRIM(P_OPERACION)) = 'D' THEN
        DELETE FROM LEHZ_PASAJE_BAJADA WHERE ID_BOLETO = P_ID_BOLETO;
        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20112, 'El boleto no tiene bajada registrada');
        END IF;
    ELSE
        RAISE_APPLICATION_ERROR(-20113, 'Operacion invalida (I/U/D)');
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20114, 'Boleto inexistente');
    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20115, 'El boleto ya tiene bajada');
END;
/

-- Consulta para interfaz PHP: terminales elegibles por viaje, ordenados.
-- Sustituir :ID_VIAJE por variable vinculada (bind).
SELECT PB.ID_PUNTO_BAJADA, PB.ID_TERMINAL, T.NOMBRE AS TERMINAL,
       C.NOMBRE_COMUNA,
       CASE WHEN PB.ID_TERMINAL = R.ID_TERMINAL_DESTINO
            THEN NVL((SELECT MAX(ORDEN_PARADA) FROM LEHZ_RUTA_PARADA RP
                      WHERE RP.ID_RUTA = R.ID_RUTA), 0) + 1
            ELSE (SELECT RP.ORDEN_PARADA FROM LEHZ_RUTA_PARADA RP
                  WHERE RP.ID_RUTA = R.ID_RUTA AND RP.ID_TERMINAL = PB.ID_TERMINAL)
       END AS ORDEN
  FROM LEHZ_VIAJE V
  JOIN LEHZ_RUTA R ON R.ID_RUTA = V.ID_RUTA
  JOIN LEHZ_PUNTO_BAJADA PB ON PB.ID_RUTA = R.ID_RUTA
  JOIN LEHZ_TERMINAL T ON T.ID_TERMINAL = PB.ID_TERMINAL
  JOIN LEHZ_COMUNA C ON C.ID_COMUNA = T.ID_COMUNA
 WHERE V.ID_VIAJE = :ID_VIAJE
   AND PB.ID_TERMINAL <> R.ID_TERMINAL_ORIGEN
   AND (PB.ID_TERMINAL = R.ID_TERMINAL_DESTINO OR EXISTS
       (SELECT 1 FROM LEHZ_RUTA_PARADA RP WHERE RP.ID_RUTA = R.ID_RUTA
        AND RP.ID_TERMINAL = PB.ID_TERMINAL))
 ORDER BY ORDEN;

-- Consulta de las bajadas registradas:
SELECT B.ID_BOLETO, B.ID_VIAJE, PB.ID_PUNTO_BAJADA,
       T.ID_TERMINAL, T.NOMBRE AS TERMINAL_BAJADA, C.NOMBRE_COMUNA
  FROM LEHZ_PASAJE_BAJADA X
  JOIN LEHZ_BOLETO B ON B.ID_BOLETO = X.ID_BOLETO
  JOIN LEHZ_PUNTO_BAJADA PB ON PB.ID_PUNTO_BAJADA = X.ID_PUNTO_BAJADA
  JOIN LEHZ_TERMINAL T ON T.ID_TERMINAL = PB.ID_TERMINAL
  JOIN LEHZ_COMUNA C ON C.ID_COMUNA = T.ID_COMUNA
 ORDER BY B.ID_VIAJE, B.ID_BOLETO;

