ALTER SESSION SET CURRENT_SCHEMA = LEHZ;

CREATE OR REPLACE PROCEDURE LEHZ_PS_REP_OCUPACION_ASIENTOS(
    p_cursor OUT SYS_REFCURSOR
) IS
BEGIN
    OPEN p_cursor FOR
        SELECT v.ID_VIAJE,
               v.FECHA_VIAJE,
               'Ruta ID: ' || r.ID_RUTA AS TRAYECTO_DETALLE,
               b.PATENTE_BUS,
               b.CAPACIDAD AS CAPACIDAD_TOTAL,
               COUNT(bol.ID_BOLETO) AS ASIENTOS_VENDIDOS,
               (b.CAPACIDAD - COUNT(bol.ID_BOLETO)) AS ASIENTOS_DISPONIBLES
        FROM LEHZ_VIAJE v
        INNER JOIN LEHZ_RUTA r ON v.ID_RUTA = r.ID_RUTA
        INNER JOIN LEHZ_CONDUCE c ON v.ID_VIAJE = c.ID_VIAJE
        INNER JOIN LEHZ_BUS b ON c.PATENTE_BUS = b.PATENTE_BUS
        LEFT JOIN LEHZ_BOLETO bol ON v.ID_VIAJE = bol.ID_VIAJE AND bol.PATENTE_BUS = b.PATENTE_BUS
        GROUP BY v.ID_VIAJE, v.FECHA_VIAJE, r.ID_RUTA, b.PATENTE_BUS, b.CAPACIDAD
        ORDER BY v.FECHA_VIAJE ASC;
END LEHZ_PS_REP_OCUPACION_ASIENTOS;
