-- 11_crud_ruta_parada.sql - VERSION SIMPLIFICADA
-- Requiere tablas, columnas y secuencias creadas previamente.
-- Ejecutar conectado al esquema LEHZ (o con CURRENT_SCHEMA = LEHZ).
-- No realiza COMMIT: quien llama controla la transaccion.

CREATE OR REPLACE PROCEDURE LEHZ_CRUD_RUTA (
    P_OPERACION IN VARCHAR2,
    P_ID_RUTA IN NUMBER DEFAULT NULL,
    P_ID_ORIGEN IN NUMBER DEFAULT NULL,
    P_ID_DESTINO IN NUMBER DEFAULT NULL,
    P_HORARIO IN TIMESTAMP DEFAULT NULL,
    P_DISTANCIA IN NUMBER DEFAULT NULL,
    P_HORAS IN NUMBER DEFAULT NULL,
    P_MINUTOS IN NUMBER DEFAULT NULL
)
IS
    V_EXISTE NUMBER;
BEGIN
    IF UPPER(P_OPERACION) IN ('I', 'U') THEN
        IF P_ID_ORIGEN IS NULL OR P_ID_DESTINO IS NULL
           OR P_ID_ORIGEN = P_ID_DESTINO THEN
            RAISE_APPLICATION_ERROR(-20001, 'Origen y destino deben ser distintos');
        END IF;

        IF P_DISTANCIA < 0 OR P_HORAS < 0
           OR P_MINUTOS < 0 OR P_MINUTOS >= 60 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Distancia o duracion invalida');
        END IF;

        SELECT COUNT(*) INTO V_EXISTE
        FROM LEHZ_TERMINAL
        WHERE ID_TERMINAL IN (P_ID_ORIGEN, P_ID_DESTINO);

        IF V_EXISTE <> 2 THEN
            RAISE_APPLICATION_ERROR(-20003, 'Origen o destino inexistente');
        END IF;

        SELECT COUNT(*) INTO V_EXISTE
        FROM LEHZ_RUTA_PARADA
        WHERE ID_RUTA = P_ID_RUTA
          AND ID_TERMINAL IN (P_ID_ORIGEN, P_ID_DESTINO);

        IF V_EXISTE > 0 THEN
            RAISE_APPLICATION_ERROR(-20004, 'Origen o destino coincide con una parada');
        END IF;
    END IF;

    IF UPPER(P_OPERACION) = 'I' THEN
        INSERT INTO LEHZ_RUTA (
            ID_RUTA, ID_TERMINAL_ORIGEN, ID_TERMINAL_DESTINO,
            HORARIO, DISTANCIA, HORAS_ESTIMADAS, MINUTOS_ESTIMADOS
        ) VALUES (
            LEHZ_SEQ_RUTA.NEXTVAL, P_ID_ORIGEN, P_ID_DESTINO,
            P_HORARIO, P_DISTANCIA, P_HORAS, P_MINUTOS
        );

    ELSIF UPPER(P_OPERACION) = 'U' THEN
        UPDATE LEHZ_RUTA
        SET ID_TERMINAL_ORIGEN = P_ID_ORIGEN,
            ID_TERMINAL_DESTINO = P_ID_DESTINO,
            HORARIO = P_HORARIO,
            DISTANCIA = P_DISTANCIA,
            HORAS_ESTIMADAS = P_HORAS,
            MINUTOS_ESTIMADOS = P_MINUTOS
        WHERE ID_RUTA = P_ID_RUTA;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20005, 'Ruta no encontrada');
        END IF;

    ELSIF UPPER(P_OPERACION) = 'D' THEN
        -- Primero se verifica que la ruta exista.
        SELECT COUNT(*) INTO V_EXISTE
        FROM LEHZ_RUTA WHERE ID_RUTA = P_ID_RUTA;

        IF V_EXISTE = 0 THEN
            RAISE_APPLICATION_ERROR(-20005, 'Ruta no encontrada');
        END IF;

        -- La FK de viajes debe impedir eliminar una ruta en uso.
        -- Un SAVEPOINT evita perder paradas si falla el borrado de ruta.
        SAVEPOINT SP_BORRAR_RUTA;
        BEGIN
            DELETE FROM LEHZ_RUTA_PARADA WHERE ID_RUTA = P_ID_RUTA;
            DELETE FROM LEHZ_RUTA WHERE ID_RUTA = P_ID_RUTA;
        EXCEPTION
            WHEN OTHERS THEN
                ROLLBACK TO SP_BORRAR_RUTA;
                RAISE;
        END;

    ELSE
        RAISE_APPLICATION_ERROR(-20006, 'Operacion invalida: I, U o D');
    END IF;
END;
/

CREATE OR REPLACE PROCEDURE LEHZ_CRUD_RUTA_PARADA (
    P_OPERACION IN VARCHAR2,
    P_ID_RUTA_PARADA IN NUMBER DEFAULT NULL,
    P_ID_RUTA IN NUMBER DEFAULT NULL,
    P_ID_TERMINAL IN NUMBER DEFAULT NULL,
    P_ORDEN IN NUMBER DEFAULT NULL
)
IS
    V_ORIGEN NUMBER;
    V_DESTINO NUMBER;
    V_EXISTE NUMBER;
BEGIN
    IF UPPER(P_OPERACION) IN ('I', 'U') THEN
        IF P_ID_RUTA IS NULL OR P_ID_TERMINAL IS NULL
           OR P_ORDEN IS NULL OR P_ORDEN < 1
           OR P_ORDEN <> TRUNC(P_ORDEN) THEN
            RAISE_APPLICATION_ERROR(-20011, 'Ruta, terminal y orden valido son obligatorios');
        END IF;

        SELECT ID_TERMINAL_ORIGEN, ID_TERMINAL_DESTINO
        INTO V_ORIGEN, V_DESTINO
        FROM LEHZ_RUTA
        WHERE ID_RUTA = P_ID_RUTA;

        IF P_ID_TERMINAL IN (V_ORIGEN, V_DESTINO) THEN
            RAISE_APPLICATION_ERROR(-20012, 'La parada no puede ser origen ni destino');
        END IF;

        SELECT COUNT(*) INTO V_EXISTE
        FROM LEHZ_RUTA_PARADA
        WHERE ID_RUTA = P_ID_RUTA
          AND (P_ID_RUTA_PARADA IS NULL OR ID_RUTA_PARADA <> P_ID_RUTA_PARADA)
          AND (ID_TERMINAL = P_ID_TERMINAL OR ORDEN_PARADA = P_ORDEN);

        IF V_EXISTE > 0 THEN
            RAISE_APPLICATION_ERROR(-20013, 'Terminal u orden repetido en la ruta');
        END IF;
    END IF;

    IF UPPER(P_OPERACION) = 'I' THEN
        INSERT INTO LEHZ_RUTA_PARADA (
            ID_RUTA_PARADA, ID_RUTA, ID_TERMINAL, ORDEN_PARADA
        ) VALUES (
            LEHZ_SEQ_RUTA_PARADA.NEXTVAL, P_ID_RUTA, P_ID_TERMINAL, P_ORDEN
        );

    ELSIF UPPER(P_OPERACION) = 'U' THEN
        UPDATE LEHZ_RUTA_PARADA
        SET ID_RUTA = P_ID_RUTA,
            ID_TERMINAL = P_ID_TERMINAL,
            ORDEN_PARADA = P_ORDEN
        WHERE ID_RUTA_PARADA = P_ID_RUTA_PARADA;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20014, 'Parada no encontrada');
        END IF;

    ELSIF UPPER(P_OPERACION) = 'D' THEN
        DELETE FROM LEHZ_RUTA_PARADA
        WHERE ID_RUTA_PARADA = P_ID_RUTA_PARADA;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20014, 'Parada no encontrada');
        END IF;

    ELSE
        RAISE_APPLICATION_ERROR(-20015, 'Operacion invalida: I, U o D');
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20016, 'Ruta no encontrada');
END;
/

-- VISTA 1: puntos del trayecto en orden.
CREATE OR REPLACE VIEW LEHZ_V_RUTA_TRAYECTO AS
WITH PUNTOS AS (
    SELECT R.ID_RUTA, 0 AS ORDEN, 'ORIGEN' AS TIPO,
           R.ID_TERMINAL_ORIGEN AS ID_TERMINAL
    FROM LEHZ_RUTA R
    UNION ALL
    SELECT P.ID_RUTA, P.ORDEN_PARADA, 'PARADA', P.ID_TERMINAL
    FROM LEHZ_RUTA_PARADA P
    UNION ALL
    SELECT R.ID_RUTA,
           NVL((SELECT MAX(P.ORDEN_PARADA)
                FROM LEHZ_RUTA_PARADA P
                WHERE P.ID_RUTA = R.ID_RUTA), 0) + 1,
           'DESTINO', R.ID_TERMINAL_DESTINO
    FROM LEHZ_RUTA R
)
SELECT P.ID_RUTA, P.ORDEN, P.TIPO, P.ID_TERMINAL,
       T.NOMBRE AS NOMBRE_TERMINAL,
       C.ID_COMUNA, C.NOMBRE_COMUNA, C.ID_REGION
FROM PUNTOS P
JOIN LEHZ_TERMINAL T ON T.ID_TERMINAL = P.ID_TERMINAL
JOIN LEHZ_COMUNA C ON C.ID_COMUNA = T.ID_COMUNA;
/

-- VISTA 2: recorrido completo y totales.
CREATE OR REPLACE VIEW LEHZ_V_RUTA_RESUMEN AS
SELECT ID_RUTA,
       LISTAGG(NOMBRE_COMUNA, ' -> ')
           WITHIN GROUP (ORDER BY ORDEN) AS RECORRIDO_CIUDADES,
       LISTAGG(NOMBRE_TERMINAL, ' -> ')
           WITHIN GROUP (ORDER BY ORDEN) AS RECORRIDO_TERMINALES,
       COUNT(DISTINCT ID_COMUNA) AS TOTAL_CIUDADES,
       COUNT(DISTINCT ID_TERMINAL) AS TOTAL_TERMINALES,
       SUM(CASE WHEN TIPO = 'PARADA' THEN 1 ELSE 0 END) AS TOTAL_PARADAS
FROM LEHZ_V_RUTA_TRAYECTO
GROUP BY ID_RUTA;
/

-- CONSULTAS
SELECT * FROM LEHZ_V_RUTA_TRAYECTO ORDER BY ID_RUTA, ORDEN;
SELECT * FROM LEHZ_V_RUTA_RESUMEN ORDER BY ID_RUTA;
