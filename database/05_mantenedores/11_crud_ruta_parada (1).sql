-- 1. CRUD DE RUTAS. Los terminales deben existir y ser diferentes.
CREATE OR REPLACE PROCEDURE LEHZ_CRUD_RUTA (
    P_OPERACION IN VARCHAR2,
    P_ID_RUTA IN NUMBER,
    P_ID_ORIGEN IN NUMBER DEFAULT NULL,
    P_ID_DESTINO IN NUMBER DEFAULT NULL,
    P_HORARIO IN TIMESTAMP DEFAULT NULL,
    P_DISTANCIA IN NUMBER DEFAULT NULL,
    P_HORAS IN NUMBER DEFAULT NULL,
    P_MINUTOS IN NUMBER DEFAULT NULL
) IS
    V_EXISTE NUMBER;
    V_PARADAS NUMBER;
BEGIN
    IF UPPER(TRIM(P_OPERACION)) IN ('I','U') THEN
        IF P_ID_ORIGEN IS NULL OR P_ID_DESTINO IS NULL OR P_ID_ORIGEN = P_ID_DESTINO THEN
            RAISE_APPLICATION_ERROR(-20001, 'Origen y destino deben existir y ser diferentes');
        END IF;
        SELECT COUNT(*) INTO V_EXISTE FROM LEHZ_TERMINAL
        WHERE ID_TERMINAL IN (P_ID_ORIGEN, P_ID_DESTINO);
        IF V_EXISTE <> 2 THEN
            RAISE_APPLICATION_ERROR(-20002, 'Terminal de origen o destino inexistente');
        END IF;
        IF P_DISTANCIA < 0 OR P_HORAS < 0 OR P_MINUTOS < 0 OR P_MINUTOS >= 60 THEN
            RAISE_APPLICATION_ERROR(-20003, 'Distancia o duracion invalida');
        END IF;
    END IF;

    CASE UPPER(TRIM(P_OPERACION))
        WHEN 'I' THEN
            INSERT INTO LEHZ_RUTA (ID_RUTA, ID_TERMINAL_ORIGEN, ID_TERMINAL_DESTINO,
                                   HORARIO, DISTANCIA, HORAS_ESTIMADAS, MINUTOS_ESTIMADOS)
            VALUES (P_ID_RUTA, P_ID_ORIGEN, P_ID_DESTINO,
                    P_HORARIO, P_DISTANCIA, P_HORAS, P_MINUTOS);
        WHEN 'U' THEN
            SELECT COUNT(*) INTO V_PARADAS FROM LEHZ_RUTA_PARADA
            WHERE ID_RUTA = P_ID_RUTA AND ID_TERMINAL IN (P_ID_ORIGEN, P_ID_DESTINO);
            IF V_PARADAS > 0 THEN
                RAISE_APPLICATION_ERROR(-20004, 'Origen/destino coincide con una parada existente');
            END IF;
            UPDATE LEHZ_RUTA
            SET ID_TERMINAL_ORIGEN = P_ID_ORIGEN,
                ID_TERMINAL_DESTINO = P_ID_DESTINO,
                HORARIO = P_HORARIO, DISTANCIA = P_DISTANCIA,
                HORAS_ESTIMADAS = P_HORAS, MINUTOS_ESTIMADOS = P_MINUTOS
            WHERE ID_RUTA = P_ID_RUTA;
            IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20005,'Ruta inexistente'); END IF;
        WHEN 'D' THEN
            -- Eliminar primero las paradas. Si existen viajes que referencian la ruta,
            -- la FK de viajes impide el DELETE (se conserva integridad referencial).
            DELETE FROM LEHZ_RUTA_PARADA WHERE ID_RUTA = P_ID_RUTA;
            DELETE FROM LEHZ_RUTA WHERE ID_RUTA = P_ID_RUTA;
            IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20005,'Ruta inexistente'); END IF;
        ELSE
            RAISE_APPLICATION_ERROR(-20006,'Operacion invalida: usar I, U o D');
    END CASE;
    -- Sin COMMIT: la transaccion la controla quien llama.
END;
/

-- 2. CRUD DE PARADAS. Orden 1..N, sin repetir terminales en una ruta.
CREATE OR REPLACE PROCEDURE LEHZ_CRUD_RUTA_PARADA (
    P_OPERACION IN VARCHAR2,
    P_ID_RUTA_PARADA IN NUMBER,
    P_ID_RUTA IN NUMBER DEFAULT NULL,
    P_ID_TERMINAL IN NUMBER DEFAULT NULL,
    P_ORDEN IN NUMBER DEFAULT NULL
) IS
    V_ORIGEN NUMBER;
    V_DESTINO NUMBER;
    V_EXISTE NUMBER;
BEGIN
    IF UPPER(TRIM(P_OPERACION)) IN ('I','U') THEN
        IF P_ID_RUTA IS NULL OR P_ID_TERMINAL IS NULL OR P_ORDEN IS NULL
           OR P_ORDEN < 1 OR P_ORDEN <> TRUNC(P_ORDEN) THEN
            RAISE_APPLICATION_ERROR(-20011,'Ruta, terminal y orden entero positivo son obligatorios');
        END IF;
        SELECT ID_TERMINAL_ORIGEN, ID_TERMINAL_DESTINO
        INTO V_ORIGEN, V_DESTINO FROM LEHZ_RUTA WHERE ID_RUTA = P_ID_RUTA;
        IF P_ID_TERMINAL IN (V_ORIGEN, V_DESTINO) THEN
            RAISE_APPLICATION_ERROR(-20012,'La parada no puede ser origen ni destino');
        END IF;
        SELECT COUNT(*) INTO V_EXISTE FROM LEHZ_TERMINAL WHERE ID_TERMINAL = P_ID_TERMINAL;
        IF V_EXISTE = 0 THEN RAISE_APPLICATION_ERROR(-20013,'Terminal de parada inexistente'); END IF;
        SELECT COUNT(*) INTO V_EXISTE FROM LEHZ_RUTA_PARADA
        WHERE ID_RUTA = P_ID_RUTA AND (P_ID_RUTA_PARADA IS NULL OR ID_RUTA_PARADA <> P_ID_RUTA_PARADA)
          AND (ID_TERMINAL = P_ID_TERMINAL OR ORDEN_PARADA = P_ORDEN);
        IF V_EXISTE > 0 THEN RAISE_APPLICATION_ERROR(-20014,'Terminal u orden duplicado en la ruta'); END IF;
    END IF;
    CASE UPPER(TRIM(P_OPERACION))
        WHEN 'I' THEN
            INSERT INTO LEHZ_RUTA_PARADA (ID_RUTA_PARADA, ID_RUTA, ID_TERMINAL, ORDEN_PARADA)
            VALUES (P_ID_RUTA_PARADA, P_ID_RUTA, P_ID_TERMINAL, P_ORDEN);
        WHEN 'U' THEN
            UPDATE LEHZ_RUTA_PARADA SET ID_RUTA=P_ID_RUTA,
                ID_TERMINAL=P_ID_TERMINAL, ORDEN_PARADA=P_ORDEN
            WHERE ID_RUTA_PARADA=P_ID_RUTA_PARADA;
            IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20015,'Parada inexistente'); END IF;
        WHEN 'D' THEN
            DELETE FROM LEHZ_RUTA_PARADA WHERE ID_RUTA_PARADA=P_ID_RUTA_PARADA;
            IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20015,'Parada inexistente'); END IF;
        ELSE
            RAISE_APPLICATION_ERROR(-20016,'Operacion invalida: usar I, U o D');
    END CASE;
EXCEPTION
    WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20017,'Ruta inexistente');
END;
/

-- 3. VISTA DE RECORRIDO DETALLADO: origen -> paradas -> destino.
CREATE OR REPLACE VIEW LEHZ_V_RUTA_TRAYECTO AS
WITH PUNTOS AS (
    SELECT R.ID_RUTA, 0 AS ORDEN, 'ORIGEN' AS TIPO,
           R.ID_TERMINAL_ORIGEN AS ID_TERMINAL FROM LEHZ_RUTA R
    UNION ALL
    SELECT P.ID_RUTA, P.ORDEN_PARADA, 'PARADA', P.ID_TERMINAL
    FROM LEHZ_RUTA_PARADA P
    UNION ALL
    SELECT R.ID_RUTA,
           NVL((SELECT MAX(P.ORDEN_PARADA) FROM LEHZ_RUTA_PARADA P WHERE P.ID_RUTA=R.ID_RUTA),0)+1,
           'DESTINO', R.ID_TERMINAL_DESTINO FROM LEHZ_RUTA R
)
SELECT P.ID_RUTA, P.ORDEN, P.TIPO, P.ID_TERMINAL,
       T.NOMBRE AS NOMBRE_TERMINAL, C.ID_COMUNA, C.NOMBRE_COMUNA,
       C.ID_REGION
FROM PUNTOS P
JOIN LEHZ_TERMINAL T ON T.ID_TERMINAL=P.ID_TERMINAL
JOIN LEHZ_COMUNA C ON C.ID_COMUNA=T.ID_COMUNA;
/

-- 4. VISTA RESUMEN: lista de comunas, lista de terminales, cantidades distintas.
CREATE OR REPLACE VIEW LEHZ_V_RUTA_RESUMEN AS
SELECT ID_RUTA,
       LISTAGG(NOMBRE_COMUNA, ' -> ') WITHIN GROUP (ORDER BY ORDEN) AS RECORRIDO_CIUDADES,
       LISTAGG(NOMBRE_TERMINAL, ' -> ') WITHIN GROUP (ORDER BY ORDEN) AS RECORRIDO_TERMINALES,
       COUNT(DISTINCT ID_COMUNA) AS TOTAL_CIUDADES,
       COUNT(DISTINCT ID_TERMINAL) AS TOTAL_TERMINALES,
       SUM(CASE WHEN TIPO='PARADA' THEN 1 ELSE 0 END) AS TOTAL_PARADAS
FROM LEHZ_V_RUTA_TRAYECTO
GROUP BY ID_RUTA;
/

-- 5. CONSULTAS DE LECTURA (READ).
SELECT * FROM LEHZ_V_RUTA_TRAYECTO ORDER BY ID_RUTA, ORDEN;
SELECT * FROM LEHZ_V_RUTA_RESUMEN ORDER BY ID_RUTA;

