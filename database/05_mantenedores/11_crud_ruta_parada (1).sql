    V_N NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_N
    FROM ALL_CONSTRAINTS K JOIN ALL_CONS_COLUMNS CC
      ON CC.OWNER=K.OWNER AND CC.CONSTRAINT_NAME=K.CONSTRAINT_NAME
    WHERE K.OWNER='LEHZ' AND K.TABLE_NAME='LEHZ_RUTA' AND K.CONSTRAINT_TYPE='R'
      AND CC.COLUMN_NAME='ID_TERMINAL_ORIGEN';
    IF V_N=0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE LEHZ.LEHZ_RUTA ADD CONSTRAINT LEHZ_FK_RUTA_ORIGEN FOREIGN KEY (ID_TERMINAL_ORIGEN) REFERENCES LEHZ.LEHZ_TERMINAL(ID_TERMINAL)';
    END IF;
    SELECT COUNT(*) INTO V_N
    FROM ALL_CONSTRAINTS K JOIN ALL_CONS_COLUMNS CC
      ON CC.OWNER=K.OWNER AND CC.CONSTRAINT_NAME=K.CONSTRAINT_NAME
    WHERE K.OWNER='LEHZ' AND K.TABLE_NAME='LEHZ_RUTA' AND K.CONSTRAINT_TYPE='R'
      AND CC.COLUMN_NAME='ID_TERMINAL_DESTINO';
    IF V_N=0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE LEHZ.LEHZ_RUTA ADD CONSTRAINT LEHZ_FK_RUTA_DESTINO FOREIGN KEY (ID_TERMINAL_DESTINO) REFERENCES LEHZ.LEHZ_TERMINAL(ID_TERMINAL)';
    END IF;
