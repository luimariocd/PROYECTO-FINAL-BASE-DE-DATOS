-- REQUERIMIENTO 4.1 - VISTAS FORMATEADAS DEL ITINERARIO
-- Origen -> paradas intermedias -> destino
CREATE OR REPLACE VIEW LEHZ_V_ITINERARIO_41 AS
SELECT R.ID_RUTA, R.ID_TERMINAL_ORIGEN AS ID_TERMINAL,
       0 AS ORDEN, 'ORIGEN' AS TIPO
  FROM LEHZ_RUTA R
 WHERE R.ID_TERMINAL_ORIGEN IS NOT NULL
UNION ALL
SELECT RP.ID_RUTA, RP.ID_TERMINAL, RP.ORDEN_PARADA, 'PARADA'
  FROM LEHZ_RUTA_PARADA RP
UNION ALL
SELECT R.ID_RUTA, R.ID_TERMINAL_DESTINO,
       NVL((SELECT MAX(RP.ORDEN_PARADA) FROM LEHZ_RUTA_PARADA RP
             WHERE RP.ID_RUTA = R.ID_RUTA),0)+1, 'DESTINO'
  FROM LEHZ_RUTA R
 WHERE R.ID_TERMINAL_DESTINO IS NOT NULL;

CREATE OR REPLACE VIEW LEHZ_V_RESUMEN_RUTA_41 AS
SELECT I.ID_RUTA,
       LISTAGG(T.NOMBRE, ' -> ') WITHIN GROUP (ORDER BY I.ORDEN) AS RECORRIDO,
       COUNT(*) AS TOTAL_TERMINALES,
       COUNT(DISTINCT T.ID_COMUNA) AS TOTAL_COMUNAS,
       SUM(CASE WHEN I.TIPO = 'PARADA' THEN 1 ELSE 0 END) AS TOTAL_PARADAS
  FROM LEHZ_V_ITINERARIO_41 I
  JOIN LEHZ_TERMINAL T ON T.ID_TERMINAL = I.ID_TERMINAL
 GROUP BY I.ID_RUTA;

