-- COBERTURA: todas las comunas cargadas, incluso aquellas sin terminal registrado.
SELECT R.ID_REGION, R.NOMBRE_REGION,
       COUNT(DISTINCT C.ID_COMUNA) AS TOTAL_COMUNAS,
       COUNT(DISTINCT CASE WHEN T.ID_TERMINAL IS NOT NULL THEN C.ID_COMUNA END) AS COMUNAS_CON_TERMINAL,
       COUNT(DISTINCT CASE WHEN T.ID_TERMINAL IS NULL THEN C.ID_COMUNA END) AS COMUNAS_SIN_TERMINAL,
       COUNT(DISTINCT T.ID_TERMINAL) AS TOTAL_TERMINALES
FROM LEHZ_REGION R JOIN LEHZ_COMUNA C ON C.ID_REGION = R.ID_REGION
LEFT JOIN LEHZ_TERMINAL T ON T.ID_COMUNA = C.ID_COMUNA
WHERE R.ID_REGION BETWEEN 37 AND 52
GROUP BY R.ID_REGION, R.NOMBRE_REGION ORDER BY R.ID_REGION;

-- Listado completo de comunas sin terminal formal registrado:
SELECT R.NOMBRE_REGION, C.NOMBRE_COMUNA, C.ID_COMUNA
FROM LEHZ_COMUNA C JOIN LEHZ_REGION R ON R.ID_REGION = C.ID_REGION
WHERE R.ID_REGION BETWEEN 37 AND 52
AND NOT EXISTS (SELECT 1 FROM LEHZ_TERMINAL T WHERE T.ID_COMUNA = C.ID_COMUNA)
ORDER BY R.ID_REGION, C.NOMBRE_COMUNA;


-- Completar direcciones de terminales ya existentes, sin sobrescribir datos ingresados.
UPDATE LEHZ_TERMINAL SET CALLE = COALESCE(CALLE, 'Av. Libertador Bernardo O''Higgins'), NUMERO = COALESCE(NUMERO, 3750) WHERE UPPER(TRIM(NOMBRE)) = UPPER('Terminal Alameda') AND (CALLE IS NULL OR NUMERO IS NULL);
UPDATE LEHZ_TERMINAL SET CALLE = COALESCE(CALLE, 'Av. Libertador Bernardo O''Higgins'), NUMERO = COALESCE(NUMERO, 3850) WHERE UPPER(TRIM(NOMBRE)) = UPPER('Terminal Sur') AND (CALLE IS NULL OR NUMERO IS NULL);
