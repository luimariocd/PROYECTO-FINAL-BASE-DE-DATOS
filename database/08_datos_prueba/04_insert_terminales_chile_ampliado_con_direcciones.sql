-- COBERTURA: todas las comunas cargadas, incluso aquellas sin terminal registrado.
SELECT R.ID_REGION, R.NOMBRE_REGION,
       COUNT(DISTINCT C.ID_COMUNA) AS TOTAL_COMUNAS,
       COUNT(DISTINCT CASE WHEN T.ID_TERMINAL IS NOT NULL THEN C.ID_COMUNA END) AS COMUNAS_CON_TERMINAL,
       COUNT(DISTINCT CASE WHEN T.ID_TERMINAL IS NULL THEN C.ID_COMUNA END) AS COMUNAS_SIN_TERMINAL,
       COUNT(DISTINCT T.ID_TERMINAL) AS TOTAL_TERMINALES
FROM LEHZ_REGION R JOIN LEHZ_COMUNA C ON C.ID_REGION = R.ID_REGION
LEFT JOIN LEHZ_TERMINAL T ON T.ID_COMUNA = C.ID_COMUNA
WHERE UPPER(TRIM(R.NOMBRE_REGION)) IN (
    UPPER(TRIM('Región del Maule')),
    UPPER(TRIM('Región Metropolitana')),
    UPPER(TRIM('Región de Arica y Parinacota')),
    UPPER(TRIM('Región de Tarapacá')),
    UPPER(TRIM('Región de Antofagasta')),
    UPPER(TRIM('Región de Atacama')),
    UPPER(TRIM('Región de Coquimbo')),
    UPPER(TRIM('Región de Valparaíso')),
    UPPER(TRIM('Región de O''Higgins')),
    UPPER(TRIM('Región de Ñuble')),
    UPPER(TRIM('Región del Biobío')),
    UPPER(TRIM('Región de La Araucanía')),
    UPPER(TRIM('Región de Los Ríos')),
    UPPER(TRIM('Región de Los Lagos')),
    UPPER(TRIM('Región de Aysén')),
    UPPER(TRIM('Región de Magallanes'))
)
GROUP BY R.ID_REGION, R.NOMBRE_REGION ORDER BY R.ID_REGION;

