CREATE OR REPLACE PROCEDURE "LEHZ_PS_LOGIN" (
    p_username IN  VARCHAR2,
    p_password IN  VARCHAR2,
    p_cursor   OUT SYS_REFCURSOR
) IS
    v_hash  VARCHAR2(128);
    v_count NUMBER := 0;
BEGIN
    SELECT RAWTOHEX(STANDARD_HASH(p_password, 'SHA256'))
      INTO v_hash
      FROM DUAL;

    SELECT COUNT(*)
      INTO v_count
      FROM LEHZ_USUARIO u
     WHERE LOWER(u.USERNAME) = LOWER(TRIM(p_username))
       AND u.PASSWORD_HASH = v_hash
       AND u.ESTADO = 'ACTIVO';

    IF v_count = 0 THEN
	RAISE_APPLICATION_ERROR(-20004, 'Usuario o contrasena incorrectos, o la cuenta esta inactiva.');
    END IF;

    OPEN p_cursor FOR
	SELECT u.ID_USUARIO,
	       u.USERNAME,
	       u.NOMBRE_COMPLETO,
	       u.EMAIL,
	       r.ID_ROL,
	       r.NOMBRE_ROL
	  FROM LEHZ_USUARIO u
	  INNER JOIN LEHZ_ROL r ON u.ID_ROL = r.ID_ROL
	 WHERE LOWER(u.USERNAME) = LOWER(TRIM(p_username))
	   AND u.PASSWORD_HASH = v_hash
	   AND u.ESTADO = 'ACTIVO';
END LEHZ_PS_LOGIN;;
