	p_id_comuna := LEHZ_SEQ_COMUNA.NEXTVAL;
	INSERT INTO LEHZ_COMUNA (ID_COMUNA, NOMBRE_COMUNA, ID_REGION)
	VALUES (p_id_comuna, v_nombre, v_id_region);

