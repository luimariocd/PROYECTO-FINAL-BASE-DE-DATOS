	  FROM LEHZ_RUTA_PARADA
	 WHERE ID_RUTA = p_id_ruta
	   AND ORDEN_PARADA = p_orden
	   AND ID_RUTA_PARADA <> NVL(p_id_ruta_parada, -1);
