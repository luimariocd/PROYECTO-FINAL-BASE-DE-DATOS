-- Esta parte del código se encarga de verificar el resultado de la migracion.
SET PAGESIZE 200
SET LINESIZE 250

SELECT object_type, COUNT(*) n,
       SUM(CASE WHEN status = 'INVALID' THEN 1 ELSE 0 END) invalid
  FROM user_objects
 WHERE object_type NOT IN ('INDEX', 'LOB')
 GROUP BY object_type
 ORDER BY object_type;

SELECT 'TRIGGERS_ENABLED' v, COUNT(*) n FROM user_triggers WHERE status = 'ENABLED'
UNION ALL SELECT 'TRIGGERS_DISABLED', COUNT(*) FROM user_triggers WHERE status = 'DISABLED';

SELECT 'CONSTRAINTS_ENABLED' v, COUNT(*) n FROM user_constraints WHERE status = 'ENABLED'
UNION ALL SELECT 'CONSTRAINTS_DISABLED', COUNT(*) FROM user_constraints WHERE status = 'DISABLED';

SELECT 'BOLETO' t, COUNT(*) n FROM LEHZ_BOLETO
UNION ALL SELECT 'BAJADA', COUNT(*) FROM LEHZ_PASAJE_BAJADA
UNION ALL SELECT 'ASIENTO', COUNT(*) FROM LEHZ_ASIENTO
UNION ALL SELECT 'VIAJE', COUNT(*) FROM LEHZ_VIAJE
UNION ALL SELECT 'BUS', COUNT(*) FROM LEHZ_BUS
UNION ALL SELECT 'EMPRESA', COUNT(*) FROM LEHZ_EMPRESA
UNION ALL SELECT 'PASAJERO', COUNT(*) FROM LEHZ_PASAJERO
UNION ALL SELECT 'USUARIO', COUNT(*) FROM LEHZ_USUARIO;

SELECT 'VW_RESUMEN' v, COUNT(*) n FROM LEHZ_VW_RESUMEN
UNION ALL SELECT 'VW_COMUNAS_CHILE', COUNT(*) FROM LEHZ_VW_COMUNAS_CHILE
UNION ALL SELECT 'VW_REGIONES_CHILE', COUNT(*) FROM LEHZ_VW_REGIONES_CHILE
UNION ALL SELECT 'VW_HORARIOS', COUNT(*) FROM LEHZ_VW_HORARIOS
UNION ALL SELECT 'VW_BOLETOS', COUNT(*) FROM LEHZ_VW_BOLETOS
UNION ALL SELECT 'VW_VIAJES_DETALLE', COUNT(*) FROM LEHZ_VW_VIAJES_DETALLE;

EXIT;
