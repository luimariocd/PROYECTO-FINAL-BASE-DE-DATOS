        p_id        IN VARCHAR2,
        p_detalle   IN VARCHAR2
    ) IS
    BEGIN
        INSERT INTO LHAOMRJZ_AUDITORIA (
            ID_AUDITORIA, TABLA_AFECTADA, OPERACION, ID_REGISTRO,
            DETALLE, USUARIO_BD, FECHA_EVENTO
