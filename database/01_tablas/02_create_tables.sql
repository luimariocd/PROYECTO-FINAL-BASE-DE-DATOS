-- =========================================================================
-- MODELO RELACIONAL - SISTEMA DE TRANSPORTE REGIONAL
-- RUT y telefonos se almacenan normalizados como texto.
-- RUT: CUERPO-DV  (ej. 76123456-0, 20000003-K)
-- TELEFONO: +56XXXXXXXX / +56XXXXXXXXX
-- =========================================================================

CREATE TABLE LEHZ_REGION (
    ID_REGION     NUMBER NOT NULL,
    NOMBRE_REGION VARCHAR2(60) NOT NULL,
    CONSTRAINT PK_LEHZ_REGION PRIMARY KEY (ID_REGION),
    CONSTRAINT UQ_LEHZ_REGION_NOMBRE UNIQUE (NOMBRE_REGION)
);

CREATE TABLE LEHZ_COMUNA (
    ID_COMUNA     NUMBER NOT NULL,
    NOMBRE_COMUNA VARCHAR2(60) NOT NULL,
    ID_REGION     NUMBER NOT NULL,
    CONSTRAINT PK_LEHZ_COMUNA PRIMARY KEY (ID_COMUNA),
    CONSTRAINT FK_LEHZ_COMUNA_REGION FOREIGN KEY (ID_REGION) REFERENCES LEHZ_REGION (ID_REGION),
    CONSTRAINT UQ_LEHZ_COMUNA_REGION UNIQUE (ID_REGION, NOMBRE_COMUNA)
);

CREATE TABLE LEHZ_EMPRESA (
    RUT_EMPRESA                VARCHAR2(12) NOT NULL,
    RAZON_SOCIAL               VARCHAR2(120) NOT NULL,
    TELEFONO_EMPRESA           VARCHAR2(16) NOT NULL,
    CORREO_ELECTRONICO_EMPRESA VARCHAR2(80),
    CONSTRAINT PK_LEHZ_EMPRESA PRIMARY KEY (RUT_EMPRESA),
    CONSTRAINT CK_LEHZ_EMPRESA_RUT CHECK (REGEXP_LIKE(RUT_EMPRESA, '^[0-9]{7,8}-[0-9K]$')),
    CONSTRAINT CK_LEHZ_EMPRESA_TEL CHECK (REGEXP_LIKE(TELEFONO_EMPRESA, '^[+]56(9[0-9]{8}|2[0-9]{8}|[3-7][0-9]{7})$'))
);

CREATE TABLE LEHZ_HORARIO (
    ID_HORARIO    NUMBER NOT NULL,
    HORARIO       NUMBER NOT NULL,
    HORA_SALIDA   TIMESTAMP,
    HORA_LLEGADA  TIMESTAMP,
    CONSTRAINT PK_LEHZ_HORARIO PRIMARY KEY (ID_HORARIO),
    CONSTRAINT UQ_LEHZ_HORARIO_CODIGO UNIQUE (HORARIO),
    CONSTRAINT CK_LEHZ_HORARIO_HORAS CHECK (HORA_LLEGADA IS NULL OR HORA_SALIDA IS NULL OR HORA_LLEGADA > HORA_SALIDA)
);

CREATE TABLE LEHZ_RUTA (
    ID_RUTA            NUMBER NOT NULL,
    HORARIO            TIMESTAMP,
    DISTANCIA          NUMBER NOT NULL,
    HORAS_ESTIMADAS    NUMBER DEFAULT 0 NOT NULL,
    MINUTOS_ESTIMADOS  NUMBER DEFAULT 0 NOT NULL,
    ID_COMUNA_ORIGEN   NUMBER NOT NULL,
    ID_COMUNA_DESTINO  NUMBER NOT NULL,
    CONSTRAINT PK_LEHZ_RUTA PRIMARY KEY (ID_RUTA),
    CONSTRAINT FK_LEHZ_RUTA_ORIGEN FOREIGN KEY (ID_COMUNA_ORIGEN) REFERENCES LEHZ_COMUNA (ID_COMUNA),
    CONSTRAINT FK_LEHZ_RUTA_DESTINO FOREIGN KEY (ID_COMUNA_DESTINO) REFERENCES LEHZ_COMUNA (ID_COMUNA),
    CONSTRAINT CK_LEHZ_RUTA_DISTANCIA CHECK (DISTANCIA > 0),
    CONSTRAINT CK_LEHZ_RUTA_HORAS CHECK (HORAS_ESTIMADAS >= 0 AND MINUTOS_ESTIMADOS BETWEEN 0 AND 59),
    CONSTRAINT CK_LEHZ_RUTA_ORIGEN_DESTINO CHECK (ID_COMUNA_ORIGEN <> ID_COMUNA_DESTINO)
);

CREATE TABLE LEHZ_RUTA_PARADA (
    ID_PARADA                NUMBER NOT NULL,
    ID_RUTA                  NUMBER NOT NULL,
    ORDEN                    NUMBER NOT NULL,
    ID_COMUNA                NUMBER NOT NULL,
    DISTANCIA_DESDE_ORIGEN   NUMBER DEFAULT 0 NOT NULL,
    MINUTOS_DESDE_SALIDA     NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_LEHZ_RUTA_PARADA PRIMARY KEY (ID_PARADA),
    CONSTRAINT FK_LEHZ_PARADA_RUTA FOREIGN KEY (ID_RUTA) REFERENCES LEHZ_RUTA (ID_RUTA),
    CONSTRAINT FK_LEHZ_PARADA_COMUNA FOREIGN KEY (ID_COMUNA) REFERENCES LEHZ_COMUNA (ID_COMUNA),
    CONSTRAINT UQ_LEHZ_PARADA_ORDEN UNIQUE (ID_RUTA, ORDEN),
    CONSTRAINT CK_LEHZ_PARADA_ORDEN CHECK (ORDEN >= 1),
    CONSTRAINT CK_LEHZ_PARADA_DISTANCIA CHECK (DISTANCIA_DESDE_ORIGEN >= 0),
    CONSTRAINT CK_LEHZ_PARADA_MINUTOS CHECK (MINUTOS_DESDE_SALIDA >= 0)
);

CREATE TABLE LEHZ_PASAJERO (
    RUT_PASAJERO               VARCHAR2(12) NOT NULL,
    NOMBRE_PASAJERO            VARCHAR2(100) NOT NULL,
    APELLIDO1_PASAJERO         VARCHAR2(80) NOT NULL,
    APELLIDO2_PASAJERO         VARCHAR2(80),
    TELEFONO_PASAJERO          VARCHAR2(16) NOT NULL,
    CORREO_ELECTRONICO_PASAJERO VARCHAR2(80),
    CONSTRAINT PK_LEHZ_PASAJERO PRIMARY KEY (RUT_PASAJERO),
    CONSTRAINT CK_LEHZ_PASAJERO_RUT CHECK (REGEXP_LIKE(RUT_PASAJERO, '^[0-9]{7,8}-[0-9K]$')),
    CONSTRAINT CK_LEHZ_PASAJERO_TEL CHECK (REGEXP_LIKE(TELEFONO_PASAJERO, '^[+]569[0-9]{8}$'))
);

CREATE TABLE LEHZ_CONDUCTOR (
    RUT_CONDUCTOR          VARCHAR2(12) NOT NULL,
    NOMBRE_CONDUCTOR       VARCHAR2(100) NOT NULL,
    APELLIDO1_CONDUCTOR    VARCHAR2(80) NOT NULL,
    APELLIDO2_CONDUCTOR    VARCHAR2(80),
    TELEFONO_CONDUCTOR     VARCHAR2(16) NOT NULL,
    TIPO_LICENCIA          VARCHAR2(5) NOT NULL,
    VENCIMIENTO_LICENCIA   DATE NOT NULL,
    RUT_EMPRESA            VARCHAR2(12) NOT NULL,
    CONSTRAINT PK_LEHZ_CONDUCTOR PRIMARY KEY (RUT_CONDUCTOR),
    CONSTRAINT FK_LEHZ_CONDUCTOR_EMPRESA FOREIGN KEY (RUT_EMPRESA) REFERENCES LEHZ_EMPRESA (RUT_EMPRESA),
    CONSTRAINT CK_LEHZ_CONDUCTOR_RUT CHECK (REGEXP_LIKE(RUT_CONDUCTOR, '^[0-9]{7,8}-[0-9K]$')),
    CONSTRAINT CK_LEHZ_CONDUCTOR_TEL CHECK (REGEXP_LIKE(TELEFONO_CONDUCTOR, '^[+]569[0-9]{8}$'))
);

CREATE TABLE LEHZ_MECANICO (
    RUT_MECANICO         VARCHAR2(12) NOT NULL,
    NOMBRE_MECANICO      VARCHAR2(100) NOT NULL,
    APELLIDO1_MECANICO   VARCHAR2(80) NOT NULL,
    APELLIDO2_MECANICO   VARCHAR2(80),
    TELEFONO_MECANICO    VARCHAR2(16) NOT NULL,
    ESPECIALIDAD         VARCHAR2(40),
    RUT_EMPRESA          VARCHAR2(12) NOT NULL,
    CONSTRAINT PK_LEHZ_MECANICO PRIMARY KEY (RUT_MECANICO),
    CONSTRAINT FK_LEHZ_MECANICO_EMPRESA FOREIGN KEY (RUT_EMPRESA) REFERENCES LEHZ_EMPRESA (RUT_EMPRESA),
    CONSTRAINT CK_LEHZ_MECANICO_RUT CHECK (REGEXP_LIKE(RUT_MECANICO, '^[0-9]{7,8}-[0-9K]$')),
    CONSTRAINT CK_LEHZ_MECANICO_TEL CHECK (REGEXP_LIKE(TELEFONO_MECANICO, '^[+]569[0-9]{8}$'))
);

CREATE TABLE LEHZ_BUS (
    PATENTE_BUS      VARCHAR2(8) NOT NULL,
    MARCA            VARCHAR2(30),
    MODELO           VARCHAR2(30),
    ANIO_FABRICACION NUMBER,
    CAPACIDAD        NUMBER,
    RUT_EMPRESA      VARCHAR2(12) NOT NULL,
    CONSTRAINT PK_LEHZ_BUS PRIMARY KEY (PATENTE_BUS),
    CONSTRAINT FK_LEHZ_BUS_EMPRESA FOREIGN KEY (RUT_EMPRESA) REFERENCES LEHZ_EMPRESA (RUT_EMPRESA),
    CONSTRAINT CK_LEHZ_BUS_PATENTE CHECK (REGEXP_LIKE(PATENTE_BUS, '^[A-Z0-9]{6}$')),
    CONSTRAINT CK_LEHZ_BUS_ANIO CHECK (ANIO_FABRICACION IS NULL OR ANIO_FABRICACION BETWEEN 1950 AND 2100),
    CONSTRAINT CK_LEHZ_BUS_CAPACIDAD CHECK (CAPACIDAD IS NULL OR CAPACIDAD BETWEEN 1 AND 100)
);

CREATE TABLE LEHZ_VIAJE (
    ID_VIAJE    NUMBER NOT NULL,
    FECHA_VIAJE DATE NOT NULL,
    ID_HORARIO  NUMBER NOT NULL,
    ID_RUTA     NUMBER NOT NULL,
    CONSTRAINT PK_LEHZ_VIAJE PRIMARY KEY (ID_VIAJE),
    CONSTRAINT FK_LEHZ_VIAJE_HORARIO FOREIGN KEY (ID_HORARIO) REFERENCES LEHZ_HORARIO (ID_HORARIO),
    CONSTRAINT FK_LEHZ_VIAJE_RUTA FOREIGN KEY (ID_RUTA) REFERENCES LEHZ_RUTA (ID_RUTA),
    CONSTRAINT UQ_LEHZ_VIAJE_PROGRAMADO UNIQUE (FECHA_VIAJE, ID_HORARIO, ID_RUTA)
);

CREATE TABLE LEHZ_TERMINAL (
    ID_TERMINAL NUMBER NOT NULL,
    NOMBRE      VARCHAR2(80) NOT NULL,
    CALLE       VARCHAR2(60),
    NUMERO      NUMBER,
    ID_COMUNA   NUMBER NOT NULL,
    CONSTRAINT PK_LEHZ_TERMINAL PRIMARY KEY (ID_TERMINAL),
    CONSTRAINT FK_LEHZ_TERMINAL_COMUNA FOREIGN KEY (ID_COMUNA) REFERENCES LEHZ_COMUNA (ID_COMUNA),
    CONSTRAINT CK_LEHZ_TERMINAL_NUMERO CHECK (NUMERO IS NULL OR NUMERO > 0)
);

CREATE TABLE LEHZ_MANTENCION (
    ID_MANTENCION          NUMBER NOT NULL,
    FECHA_MANTENCION       DATE NOT NULL,
    DESCRIPCION_MANTENCION VARCHAR2(500),
    COSTO_MANTENCION       NUMBER NOT NULL,
    RUT_MECANICO           VARCHAR2(12) NOT NULL,
    PATENTE_BUS            VARCHAR2(8) NOT NULL,
    CONSTRAINT PK_LEHZ_MANTENCION PRIMARY KEY (ID_MANTENCION),
    CONSTRAINT FK_LEHZ_MANTENCION_MECANICO FOREIGN KEY (RUT_MECANICO) REFERENCES LEHZ_MECANICO (RUT_MECANICO),
    CONSTRAINT FK_LEHZ_MANTENCION_BUS FOREIGN KEY (PATENTE_BUS) REFERENCES LEHZ_BUS (PATENTE_BUS),
    CONSTRAINT CK_LEHZ_MANTENCION_COSTO CHECK (COSTO_MANTENCION >= 0)
);

CREATE TABLE LEHZ_ASIENTO (
    NUMERO_ASIENTO NUMBER NOT NULL,
    PATENTE_BUS    VARCHAR2(8) NOT NULL,
    UBICACION      VARCHAR2(20),
    CONSTRAINT PK_LEHZ_ASIENTO PRIMARY KEY (NUMERO_ASIENTO, PATENTE_BUS),
    CONSTRAINT FK_LEHZ_ASIENTO_BUS FOREIGN KEY (PATENTE_BUS) REFERENCES LEHZ_BUS (PATENTE_BUS),
    CONSTRAINT CK_LEHZ_ASIENTO_NUMERO CHECK (NUMERO_ASIENTO >= 1)
);

CREATE TABLE LEHZ_CONDUCE (
    RUT_CONDUCTOR VARCHAR2(12) NOT NULL,
    PATENTE_BUS   VARCHAR2(8) NOT NULL,
    ID_VIAJE      NUMBER NOT NULL,
    CONSTRAINT PK_LEHZ_CONDUCE PRIMARY KEY (RUT_CONDUCTOR, PATENTE_BUS, ID_VIAJE),
    CONSTRAINT FK_LEHZ_CONDUCE_CONDUCTOR FOREIGN KEY (RUT_CONDUCTOR) REFERENCES LEHZ_CONDUCTOR (RUT_CONDUCTOR),
    CONSTRAINT FK_LEHZ_CONDUCE_BUS FOREIGN KEY (PATENTE_BUS) REFERENCES LEHZ_BUS (PATENTE_BUS),
    CONSTRAINT FK_LEHZ_CONDUCE_VIAJE FOREIGN KEY (ID_VIAJE) REFERENCES LEHZ_VIAJE (ID_VIAJE)
);

CREATE TABLE LEHZ_UTILIZAN (
    ID_TERMINAL NUMBER NOT NULL,
    RUT_EMPRESA VARCHAR2(12) NOT NULL,
    CONSTRAINT PK_LEHZ_UTILIZAN PRIMARY KEY (ID_TERMINAL, RUT_EMPRESA),
    CONSTRAINT FK_LEHZ_UTILIZAN_TERMINAL FOREIGN KEY (ID_TERMINAL) REFERENCES LEHZ_TERMINAL (ID_TERMINAL),
    CONSTRAINT FK_LEHZ_UTILIZAN_EMPRESA FOREIGN KEY (RUT_EMPRESA) REFERENCES LEHZ_EMPRESA (RUT_EMPRESA)
);

CREATE TABLE LEHZ_BOLETO (
    ID_BOLETO             NUMBER NOT NULL,
    FECHA_EMISION_BOLETO  DATE NOT NULL,
    HORA_EMISION_BOLETO   TIMESTAMP,
    VALOR_BOLETO          NUMBER NOT NULL,
    RUT_PASAJERO          VARCHAR2(12) NOT NULL,
    ID_VIAJE              NUMBER NOT NULL,
    NUMERO_ASIENTO        NUMBER NOT NULL,
    PATENTE_BUS           VARCHAR2(8) NOT NULL,
    CONSTRAINT PK_LEHZ_BOLETO PRIMARY KEY (ID_BOLETO),
    CONSTRAINT FK_LEHZ_BOLETO_PASAJERO FOREIGN KEY (RUT_PASAJERO) REFERENCES LEHZ_PASAJERO (RUT_PASAJERO),
    CONSTRAINT FK_LEHZ_BOLETO_VIAJE FOREIGN KEY (ID_VIAJE) REFERENCES LEHZ_VIAJE (ID_VIAJE),
    CONSTRAINT FK_LEHZ_BOLETO_ASIENTO FOREIGN KEY (NUMERO_ASIENTO, PATENTE_BUS) REFERENCES LEHZ_ASIENTO (NUMERO_ASIENTO, PATENTE_BUS),
    CONSTRAINT UQ_LEHZ_BOLETO_ASIENTO UNIQUE (ID_VIAJE, NUMERO_ASIENTO, PATENTE_BUS),
    CONSTRAINT CK_LEHZ_BOLETO_VALOR CHECK (VALOR_BOLETO > 0)
);

CREATE TABLE LEHZ_PAGO (
    ID_PAGO       NUMBER NOT NULL,
    FECHA_PAGO    DATE NOT NULL,
    MONTO_PAGO    NUMBER NOT NULL,
    METODO_PAGO   VARCHAR2(20) NOT NULL,
    ID_BOLETO     NUMBER NOT NULL,
    RUT_PASAJERO  VARCHAR2(12) NOT NULL,
    CONSTRAINT PK_LEHZ_PAGO PRIMARY KEY (ID_PAGO),
    CONSTRAINT UQ_LEHZ_PAGO_BOLETO UNIQUE (ID_BOLETO),
    CONSTRAINT FK_LEHZ_PAGO_BOLETO FOREIGN KEY (ID_BOLETO) REFERENCES LEHZ_BOLETO (ID_BOLETO),
    CONSTRAINT FK_LEHZ_PAGO_PASAJERO FOREIGN KEY (RUT_PASAJERO) REFERENCES LEHZ_PASAJERO (RUT_PASAJERO),
    CONSTRAINT CK_LEHZ_PAGO_MONTO CHECK (MONTO_PAGO > 0),
    CONSTRAINT CK_LEHZ_PAGO_METODO CHECK (METODO_PAGO IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA'))
);

