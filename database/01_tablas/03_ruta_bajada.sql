-- Paradas intermedias 
CREATE TABLE LEHZ_RUTA_PARADA (
    ID_RUTA_PARADA NUMBER PRIMARY KEY,
    ID_RUTA NUMBER NOT NULL REFERENCES LEHZ_RUTA(ID_RUTA),
    ID_TERMINAL NUMBER NOT NULL REFERENCES LEHZ_TERMINAL(ID_TERMINAL),
    ORDEN_PARADA NUMBER NOT NULL,
    CONSTRAINT LEHZ_UQ_RP_RUTA_TER UNIQUE(ID_RUTA, ID_TERMINAL),
    CONSTRAINT LEHZ_UQ_RP_RUTA_ORD UNIQUE(ID_RUTA, ORDEN_PARADA),
    CONSTRAINT LEHZ_CK_RP_ORD CHECK(ORDEN_PARADA >= 1 AND ORDEN_PARADA = TRUNC(ORDEN_PARADA))
);

-- Terminales habilitados para bajada en una ruta.
-- SOLO pueden ser paradas intermedias o el destino; se valida en el gestor.
CREATE TABLE LEHZ_PUNTO_BAJADA (
    ID_PUNTO_BAJADA NUMBER NOT NULL,
    ID_RUTA NUMBER NOT NULL,
    ID_TERMINAL NUMBER NOT NULL,
    CONSTRAINT LEHZ_PK_PUNTO_BAJADA PRIMARY KEY (ID_PUNTO_BAJADA),
    CONSTRAINT LEHZ_FK_PB_RUTA FOREIGN KEY (ID_RUTA) REFERENCES LEHZ_RUTA(ID_RUTA),
    CONSTRAINT LEHZ_FK_PB_TERMINAL FOREIGN KEY (ID_TERMINAL) REFERENCES LEHZ_TERMINAL(ID_TERMINAL),
    CONSTRAINT LEHZ_UQ_PB_RUTA_TERMINAL UNIQUE (ID_RUTA, ID_TERMINAL),
    CONSTRAINT LEHZ_UQ_PB_ID_RUTA UNIQUE (ID_PUNTO_BAJADA, ID_RUTA)
);

CREATE SEQUENCE LEHZ_SEQ_PUNTO_BAJADA START WITH 1 INCREMENT BY 1 NOCACHE;

-- Tabla de elección por boleto. Si ya existe, NO ejecutar este CREATE TABLE:
CREATE TABLE LEHZ_PASAJE_BAJADA (
    ID_PASAJE_BAJADA NUMBER NOT NULL,
    ID_BOLETO NUMBER NOT NULL,
    ID_PUNTO_BAJADA NUMBER NOT NULL,
    CONSTRAINT LEHZ_PK_PASAJE_BAJADA PRIMARY KEY (ID_PASAJE_BAJADA),
    CONSTRAINT LEHZ_FK_PAS_BAJ_BOLETO FOREIGN KEY (ID_BOLETO)
        REFERENCES LEHZ_BOLETO(ID_BOLETO),
    CONSTRAINT LEHZ_FK_PAS_BAJ_PUNTO FOREIGN KEY (ID_PUNTO_BAJADA)
        REFERENCES LEHZ_PUNTO_BAJADA(ID_PUNTO_BAJADA),
    CONSTRAINT LEHZ_UQ_PAS_BAJ_BOLETO UNIQUE (ID_BOLETO)
);

CREATE SEQUENCE LEHZ_SEQ_PASAJE_BAJADA START WITH 1 INCREMENT BY 1 NOCACHE;

