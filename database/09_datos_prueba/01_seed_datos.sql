    PROCEDURE crear_boleto(
        p_rut       IN VARCHAR2,
        p_viaje     IN NUMBER,
        p_asiento   IN NUMBER,
        p_patente   IN VARCHAR2,
        p_metodo    IN VARCHAR2,
        p_terminal  IN NUMBER DEFAULT NULL,
        p_estado    IN VARCHAR2 DEFAULT 'EMITIDO',
        p_motivo    IN VARCHAR2 DEFAULT NULL
    ) IS
    BEGIN
        v_tarifa := LHAOMRJZ_FN_CALCULAR_TARIFA_BUS(p_viaje, p_patente, p_terminal);
        v_boleto := LHAOMRJZ_SEQ_BOLETO.NEXTVAL;

        INSERT INTO LHAOMRJZ_BOLETO (
            ID_BOLETO, FECHA_EMISION_BOLETO, HORA_EMISION_BOLETO, VALOR_BOLETO,
            RUT_PASAJERO, ID_VIAJE, NUMERO_ASIENTO, PATENTE_BUS, ESTADO,
            FECHA_ANULACION, MOTIVO_ANULACION
        ) VALUES (
            v_boleto, SYSDATE, SYSTIMESTAMP, v_tarifa,
            p_rut, p_viaje, p_asiento, p_patente, p_estado,
            CASE WHEN p_estado = 'ANULADO' THEN SYSDATE END,
            CASE WHEN p_estado = 'ANULADO' THEN p_motivo END
        );

        IF p_estado = 'EMITIDO' THEN
            INSERT INTO LHAOMRJZ_PAGO (
                ID_PAGO, FECHA_PAGO, MONTO_PAGO, METODO_PAGO, ID_BOLETO, RUT_PASAJERO
            ) VALUES (
                LHAOMRJZ_SEQ_PAGO.NEXTVAL, SYSDATE, v_tarifa, p_metodo, v_boleto, p_rut
            );
        END IF;

        IF p_terminal IS NOT NULL THEN
            INSERT INTO LHAOMRJZ_PASAJE_BAJADA (
                ID_BAJADA, ID_BOLETO, ID_TERMINAL_BAJADA, OBSERVACION, FECHA_REGISTRO
            ) VALUES (
                LHAOMRJZ_SEQ_PASAJE_BAJADA.NEXTVAL, v_boleto, p_terminal,
                'Bajada registrada en carga inicial', SYSDATE
            );
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END;
